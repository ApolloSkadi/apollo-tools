/**
 * reicon-sync.js
 *
 * Reads Reicon icon source files (from node_modules/reicon or a directory
 * passed via REICON_SRC) and emits `src/icons/reicon-data.js`.
 *
 * The emitted file is the single source of truth for the icons used across
 * the app. It contains the raw SVG inner markup for each icon in two
 * weights: `O` (outline) and `F` (filled). At runtime we wrap that markup
 * with an <svg> tag, recolor `currentColor`, and render it as a base64 / data
 * URI `background-image`, which is the only reliable way to draw SVG inside a
 * WeChat mini program (no <svg> DOM node, no Image svg support).
 *
 * Reicon: https://reicon.dev | MIT License
 */
const fs = require('node:fs')
const path = require('node:path')

const ROOT = path.resolve(__dirname, '..')
const DEFAULT_SRC = path.join(ROOT, 'node_modules', 'reicon', 'icons')
const SRC = process.env.REICON_SRC || DEFAULT_SRC
const OUT = path.join(ROOT, 'src', 'icons', 'reicon-data.js')

