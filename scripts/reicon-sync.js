function extractBlock(source, key) {
  // The Reicon source files hold the markup inside backticks: `O: \`<svg/>\``.
  // Build the pattern from plain strings so backticks don't clash with
  // template literal syntax.
  const bt = String.fromCharCode(96)
  const pattern = key + ':\\s*' + bt + '([\\s\\S]*?)' + bt
  const re = new RegExp(pattern)
  const match = source.match(re)
  return match ? match[1] : null
}

const record = {}
const missing = []

for (const name of ICON_NAMES) {
  const file = path.join(SRC, `${name}.js`)
  if (!fs.existsSync(file)) {
    missing.push(name)
    continue
  }
  const source = fs.readFileSync(file, 'utf8')
  const O = extractBlock(source, 'O')
  const F = extractBlock(source, 'F')
  record[name] = { O, F }
}

if (missing.length) {
  console.warn(`[reicon-sync] Missing icon source files: ${missing.join(', ')}`)
}

const body = Object.keys(record)
  .sort()
  .map((name) => {
    const icon = record[name]
    const o = icon.O ? JSON.stringify(icon.O) : 'null'
    const f = icon.F ? JSON.stringify(icon.F) : 'null'
    return `  ${name}: { O: ${o}, F: ${f} },`
  })
  .join('\n')

const banner = `/**
 * Auto-generated by scripts/reicon-sync.js — DO NOT EDIT.
 * Icons source: https://reicon.dev (MIT License), extracted from the
 * \`reicon\` npm package. Icon markup uses currentColor so it can be tinted.
 *
 * Regenerate with:  node scripts/reicon-sync.js
 */

export const REICON = {
${body}
}
`

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, banner, 'utf8')

console.log(`[reicon-sync] Wrote ${Object.keys(record).length} icons -> ${path.relative(ROOT, OUT)}`)
console.log(`[reicon-sync] Source: ${SRC}`)
