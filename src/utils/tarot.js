/**
 * Fisher-Yates shuffle returning a new array
 */
export function shuffleDeck() {
  const deck = [...MAJOR_ARCANA]
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[deck[i], deck[j]] = [deck[j], deck[i]]
  }
  return deck
}

/**
 * Interpret the fortune based on three selected cards.
 * Returns a structured result with position-specific meanings and a combined summary.
 */
export function interpretFortune(pastCard, presentCard, futureCard) {
  const summary = [
    '回顾过往，' + pastCard.past,
    '放眼当下，' + presentCard.present,
    '展望未来，' + futureCard.future,
    '综合来看，' + pastCard.keywords[0] + '的' + pastCard.name + '奠定了你的基础，'
      + presentCard.name + '带来的' + presentCard.keywords[0] + '正在影响当下，'
      + '而' + futureCard.name + '预示着' + futureCard.keywords[0] + '的前景。'
      + '让过去的智慧指引现在的行动，以此刻的觉知拥抱未来的可能。',
  ].join('\n\n')

  return {
    past: pastCard,
    present: presentCard,
    future: futureCard,
    summary,
  }
}

